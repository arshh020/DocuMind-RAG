"""Evaluation set format and IO.

One JSON object per line. Minimal, diffable, and reviewable in a pull request:

    {"id": "q001",
     "question": "How do I center a div with flexbox?",
     "gold_chunk_ids": ["a1b2c3d4e5f6a7b8"],
     "gold_answer": "Set display:flex plus justify-content and align-items.",
     "source": "files/en-us/web/css/flexbox.md",
     "verified": true,
     "tags": ["css", "layout"]}

The ``verified`` flag is the honest part of this design. Questions generated by
an LLM start as ``verified: false``. You read a sample and flip them to true.
When you report numbers you report both the full set and the verified subset,
because synthetic eval sets have a known bias: the generator saw the chunk while
writing the question, so its phrasing leaks chunk vocabulary and INFLATES
lexical retrieval scores. Anyone senior will ask about this. Having the answer
ready -- and the verified subset to back it up -- is a genuine signal of rigor.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, List, Sequence, Set


@dataclass
class EvalExample:
    """A single labelled evaluation question."""

    id: str
    question: str
    gold_chunk_ids: List[str] = field(default_factory=list)
    gold_answer: str = ""
    source: str = ""
    verified: bool = False
    tags: List[str] = field(default_factory=list)

    @property
    def relevant(self) -> Set[str]:
        return set(self.gold_chunk_ids)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "EvalExample":
        known = set(cls.__dataclass_fields__)
        return cls(**{k: v for k, v in data.items() if k in known})


def load_eval_set(path: str | Path) -> List[EvalExample]:
    """Load a JSONL eval set, skipping blank lines and comment lines."""
    file_path = Path(path)
    if not file_path.is_file():
        raise FileNotFoundError(
            f"eval set not found: {file_path}\n"
            "Generate one with: python scripts/make_evalset.py"
        )

    examples: List[EvalExample] = []
    with file_path.open("r", encoding="utf-8") as handle:
        for line_number, raw in enumerate(handle, start=1):
            line = raw.strip()
            if not line or line.startswith("//"):
                continue
            try:
                examples.append(EvalExample.from_dict(json.loads(line)))
            except json.JSONDecodeError as exc:
                raise ValueError(
                    f"{file_path}:{line_number} is not valid JSON: {exc}"
                ) from exc
    return examples


def save_eval_set(examples: Iterable[EvalExample], path: str | Path) -> int:
    """Write examples as JSONL. Returns the number written."""
    file_path = Path(path)
    file_path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with file_path.open("w", encoding="utf-8") as handle:
        for example in examples:
            handle.write(json.dumps(example.to_dict(), ensure_ascii=False) + "\n")
            count += 1
    return count


def filter_verified(examples: Sequence[EvalExample]) -> List[EvalExample]:
    return [e for e in examples if e.verified]


def describe_eval_set(examples: Sequence[EvalExample]) -> Dict[str, Any]:
    """Summary stats, printed by the eval runner so results are self-documenting."""
    verified = filter_verified(examples)
    multi_gold = [e for e in examples if len(e.gold_chunk_ids) > 1]
    tags: Dict[str, int] = {}
    for example in examples:
        for tag in example.tags:
            tags[tag] = tags.get(tag, 0) + 1
    return {
        "total": len(examples),
        "verified": len(verified),
        "multi_gold": len(multi_gold),
        "tags": dict(sorted(tags.items(), key=lambda kv: -kv[1])),
    }


__all__ = (
    "EvalExample",
    "load_eval_set",
    "save_eval_set",
    "filter_verified",
    "describe_eval_set",
)
